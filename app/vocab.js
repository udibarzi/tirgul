/**
 * Play the recorded audio for an English word/phrase; fall back to the
 * browser voice if there's no recording. Autoplay blocks are ignored
 * (the user can tap 🔊).
 */
let _vocabAudio = null;
function playEnglish(text) {
  if (_vocabAudio) { _vocabAudio.pause(); _vocabAudio = null; }
  if ('speechSynthesis' in window) window.speechSynthesis.cancel();
  const audio = new Audio(VOCAB_AUDIO_BASE + vocabSlug(text) + '.mp3');
  _vocabAudio = audio;
  let fellBack = false;
  const fallback = () => { if (!fellBack && _vocabAudio === audio) { fellBack = true; speakEnglish(text); } };
  audio.addEventListener('error', fallback);
  const p = audio.play();
  if (p && p.catch) p.catch(e => { if (e && e.name !== 'NotAllowedError' && e.name !== 'AbortError') fallback(); });
}

/** Read English aloud (browser text-to-speech). */
function speakEnglish(text) {
  if (!('speechSynthesis' in window)) return;
  window.speechSynthesis.cancel();
  const u = new SpeechSynthesisUtterance(text);
  u.lang = 'en-US';
  u.rate = 0.85;
  const voices = window.speechSynthesis.getVoices();
  const v = voices.find(v => v.lang === 'en-US') || voices.find(v => v.lang && v.lang.startsWith('en'));
  if (v) u.voice = v;
  window.speechSynthesis.speak(u);
}

