/**
 * vocab.js — English vocabulary & sentence practice engine.
 *
 * A vocab topic is a content JSON with "type": "vocab" and one or both of:
 *   "words":     [{ "en": "flower", "he": "פרח", "group": "noun", "alt": [...] }]
 *   "sentences": [{ "en": "I'm hungry.", "he": "אני רעבה.", "blank": "hungry",
 *                   "choices": ["thirsty", ...] }]
 * (see docs/CONTENT-FORMAT.md). Each array is a LEVEL (words / sentences);
 * questions are GENERATED at runtime from the items, so adding content
 * needs no question writing.
 *
 * Question kinds:
 *   en-he  — English shown, pick the Hebrew meaning (multiple choice)
 *   he-en  — Hebrew shown, pick the English (multiple choice)
 *   write  — Hebrew shown, type the English (spelling; words level)
 *   listen — English audio played (text hidden), pick the Hebrew meaning
 *   order  — Hebrew shown, tap shuffled English word tiles into order
 *   cloze  — sentence with a gap ("blank"), pick the missing word. Uses the
 *            item's "choices" as distractors (tense practice) or else words
 *            from the topic's word list.
 *   speak  — Hebrew shown, say it in English (browser speech recognition)
 * Per level, a topic may restrict kinds: "modes" (words), "sentenceModes".
 *
 * Audio: recordings live in audio/en/{vocabSlug(en)}.mp3, generated by
 * _build_audio.py with a local TTS voice. If a file is missing, playback
 * falls back to the browser's speechSynthesis.
 *
 * English text is NEVER passed through fixBidi() — it's rendered with
 * escapeHtml() inside dir="ltr" elements instead.
 *
 * Depends on core.js (shuffle).
 */

const VOCAB_MODES = {
  'mix':    { label: 'מבחן מעורב',       icon: '🎯' },
  'en-he':  { label: 'מאנגלית לעברית',   icon: '🔤' },
  'he-en':  { label: 'מעברית לאנגלית',   icon: '🇮🇱' },
  'write':  { label: 'כתיבה באנגלית',    icon: '✍️' },
  'listen': { label: 'הקשבה',            icon: '🎧' },
  'order':  { label: 'בניית משפט',       icon: '🧩' },
  'cloze':  { label: 'השלמת מילה',       icon: '✏️' },
  'speak':  { label: 'להגיד בקול',       icon: '🎤' },
  'hard':   { label: 'לחיזוק',           icon: '💪' },
};

const VOCAB_KINDS = ['en-he', 'he-en', 'write', 'listen', 'order', 'cloze', 'speak'];
const VOCAB_LEVEL_KINDS = {
  words:     ['en-he', 'he-en', 'write', 'listen', 'speak'],
  sentences: ['order', 'cloze', 'en-he', 'he-en', 'listen', 'speak'],
};
const VOCAB_LEVEL_NAMES = { words: 'מילים', sentences: 'משפטים' };
const VOCAB_AUDIO_BASE = '../audio/en/';

/** Levels this topic has, in display order. */
function vocabLevels(content) {
  return ['words', 'sentences'].filter(l => Array.isArray(content[l]) && content[l].length);
}

function vocabItems(content, level) {
  return content[level] || [];
}

/** Question kinds available for a level of this topic. */
function vocabKinds(content, level) {
  level = level || 'words';
  const key = level === 'sentences' ? 'sentenceModes' : 'modes';
  let kinds = VOCAB_LEVEL_KINDS[level].slice();
  if (Array.isArray(content[key])) {
    const m = content[key].filter(k => VOCAB_KINDS.includes(k));
    if (m.length) kinds = m;
  }
  const items = vocabItems(content, level);
  if (!items.some(it => it.blank)) kinds = kinds.filter(k => k !== 'cloze');
  if (!items.some(it => orderTokens(it.en).tokens.length >= 3)) kinds = kinds.filter(k => k !== 'order');
  if (!vocabSpeechSupported()) kinds = kinds.filter(k => k !== 'speak');
  return kinds;
}

/** File-name slug for a recording. MUST match vocab_slug() in _build_audio.py. */
function vocabSlug(en) {
  return String(en).toLowerCase()
    .replace(/[’']/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

/**
 * Normalize typed English for comparison: case-insensitive, ignores
 * apostrophes and punctuation, collapses spaces (but keeps them, so
 * "diningroom" is NOT accepted for "dining room").
 */
function vocabNormalize(s) {
  return String(s)
    .toLowerCase()
    .replace(/[’‘'`´]/g, '')
    .replace(/[.!?,;:—"]/g, '')
    .replace(/[-‐–]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// ---- Per-item stats (localStorage) ----
// Separate prefix from ProgressManager ('math_app_') so landing-page totals
// don't pick these up. Keyed by the item's English text.
const VocabStats = {
  _key(topicId) {
    // Per learner when the tracker is loaded (tirgul_vocab__<name>_<topic>)
    if (typeof window !== 'undefined' && window.Tracker) return window.Tracker.vocabKey(topicId);
    return 'tirgul_vocab_' + topicId;
  },
  get(topicId) {
    try { return JSON.parse(localStorage.getItem(this._key(topicId))) || {}; }
    catch (e) { return {}; }
  },
  record(topicId, en, isCorrect) {
    const all = this.get(topicId);
    const s = all[en] || { r: 0, w: 0 };
    if (isCorrect) s.r++; else s.w++;
    s.last = isCorrect ? 1 : 0;
    all[en] = s;
    try { localStorage.setItem(this._key(topicId), JSON.stringify(all)); } catch (e) {}
  },
  /** An item "needs work" if the last answer was wrong, or it was missed more than it was hit. */
  needsWork(s) { return !!s && (s.last === 0 || s.w > s.r); },
  hardWords(topicId, items) {
    const all = this.get(topicId);
    return items.filter(w => this.needsWork(all[w.en]));
  },
};

/** Pick `count` items, favoring ones she got wrong and ones not seen yet. */
function pickVocabWords(items, count, stats) {
  if (count >= items.length) return shuffle([...items]);
  const scored = items.map(w => {
    const s = stats[w.en];
    let score = Math.random() * 2;
    if (!s) score += 1;                       // unseen
    else score += (s.w - s.r) * 0.7 + (s.last === 0 ? 2 : 0);
    return { w, score };
  });
  scored.sort((a, b) => b.score - a.score);
  return shuffle(scored.slice(0, count).map(x => x.w));
}

/** 3 distractors for `word` on `field` ('en' or 'he'), preferring the same group. */
function vocabDistractors(word, field, words) {
  const others = words.filter(o => o !== word && o[field] !== word[field]);
  const same = shuffle(others.filter(o => word.group && o.group === word.group));
  const rest = shuffle(others.filter(o => !(word.group && o.group === word.group)));
  const picked = [];
  const take = (list, n) => {
    for (const o of list) {
      if (picked.length >= n) break;
      if (!picked.includes(o[field])) picked.push(o[field]);
    }
  };
  take(same, 2);
  take(rest, 3);
  take(same, 3);
  return picked;
}

/** Distractors for a cloze gap: the item's own "choices", else similar words from the topic. */
function clozeDistractors(item, words) {
  if (Array.isArray(item.choices) && item.choices.length) return shuffle(item.choices.slice()).slice(0, 4);
  const key = vocabNormalize(item.blank);
  const match = words.find(w => vocabNormalize(w.en) === key);
  if (match) return vocabDistractors(match, 'en', words);
  return shuffle(words.map(w => w.en).filter(en => vocabNormalize(en) !== key)).slice(0, 3);
}

/** Regex finding the blank as a whole word/phrase inside the sentence. */
function clozeRegex(blank) {
  const esc = blank.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp('(^|[^A-Za-z’\'])(' + esc + ')(?![A-Za-z])');
}

/** Split a sentence into word tiles; final .!? is kept aside and shown fixed. */
function orderTokens(en) {
  const m = String(en).match(/^(.*?)([.!?]+)?$/);
  return { tokens: m[1].trim().split(/\s+/).filter(Boolean), end: m[2] || '' };
}

/** HTML for the letter-count hint shown in write mode: _ _ _ _   _ _ _ _ */
function vocabHintHtml(en) {
  return [...en].map(c => {
    if (/[a-z]/i.test(c)) return '<span class="hint-letter"></span>';
    if (c === ' ') return '<span class="hint-space"></span>';
    return '<span class="hint-char">' + escapeHtml(c) + '</span>';
  }).join('');
}

const VOCAB_PROMPTS = {
  'en-he': 'מה הפירוש?',
  'he-en': 'איך אומרים באנגלית?',
  'write': 'כתבו באנגלית:',
  'listen': 'הקשיבו ובחרו את הפירוש:',
  'order': 'סדרו את המילים למשפט:',
  'cloze': 'השלימו את המשפט:',
  'speak': 'אמרו באנגלית:',
};

/** Is `kind` usable for this item? Falls back to a kind that is. */
function fitKind(item, kind) {
  if (kind === 'cloze' && !item.blank) return orderTokens(item.en).tokens.length >= 3 ? 'order' : 'he-en';
  if (kind === 'order' && orderTokens(item.en).tokens.length < 3) return 'he-en';
  return kind;
}

function buildVocabQuestion(item, kind, items, words) {
  const q = { vocab: true, kind, word: item, text: VOCAB_PROMPTS[kind] };
  if (kind === 'write') {
    q.type = 'free-input';
    q.correct = [item.en, ...(item.alt || [])];
    return q;
  }
  if (kind === 'order') {
    const { tokens, end } = orderTokens(item.en);
    let tiles = shuffle(tokens.slice());
    for (let i = 0; i < 5 && tiles.join(' ') === tokens.join(' '); i++) tiles = shuffle(tiles);
    q.type = 'order';
    q.tiles = tiles;
    q.end = end;
    return q;
  }
  if (kind === 'speak') {
    q.type = 'speak';
    return q;
  }
  let answer, distractors, field;
  if (kind === 'cloze') {
    field = 'en';
    answer = item.blank;
    distractors = clozeDistractors(item, words);
  } else {
    field = kind === 'he-en' ? 'en' : 'he';
    answer = item[field];
    distractors = vocabDistractors(item, field, items);
  }
  const options = shuffle([answer, ...distractors]);
  q.type = 'multiple-choice';
  q.options = options;
  q.optionsLang = field;
  q.correct = options.indexOf(answer);
  return q;
}

/**
 * Generate a practice session.
 * @param {Object} content - vocab topic JSON
 * @param {string} mode - key of VOCAB_MODES
 * @param {number} count - number of questions (0 = all items)
 * @param {string} topicId
 * @param {string} level - 'words' | 'sentences'
 */
function buildVocabQuestions(content, mode, count, topicId, level) {
  level = vocabLevels(content).includes(level) ? level : vocabLevels(content)[0];
  const items = vocabItems(content, level);
  const words = content.words || [];
  const stats = VocabStats.get(topicId);
  let pool = items;
  if (mode === 'hard') {
    const hard = VocabStats.hardWords(topicId, items);
    if (hard.length) pool = hard;
  }
  const n = count > 0 ? count : pool.length;
  const chosen = pickVocabWords(pool, n, stats);

  // mix / hard: even spread of the level's kinds (speaking only on request)
  const allowed = vocabKinds(content, level).filter(k => k !== 'speak');
  let kinds;
  if (VOCAB_KINDS.includes(mode)) {
    kinds = chosen.map(() => mode);
  } else {
    kinds = shuffle(chosen.map((_, i) => allowed[i % allowed.length]));
  }
  return chosen.map((it, i) => buildVocabQuestion(it, fitKind(it, kinds[i]), items, words));
}

/** CSS class for long texts (sentences) so they fit on a phone. */
function vocabSizeClass(text) {
  return text.length > 26 ? ' longer' : text.length > 14 ? ' long' : '';
}

function vocabWordHtml(text, lang, withSpeaker) {
  return '<div class="vocab-word' + vocabSizeClass(text) + '" dir="' + (lang === 'en' ? 'ltr' : 'rtl') + '" lang="' + lang + '">' +
         escapeHtml(text) +
         (withSpeaker ? ' <button type="button" class="speak-btn" title="השמעה">🔊</button>' : '') +
         '</div>';
}

/** Sentence with the gap shown as ____ (or filled in, once answered). */
function clozeSentenceHtml(item, revealed) {
  const parts = String(item.en).split(clozeRegex(item.blank));
  // split with 2 capture groups -> [before, prefixChar, blank, after]
  const gap = revealed
    ? '<span class="cloze-gap filled">' + escapeHtml(item.blank) + '</span>'
    : '<span class="cloze-gap"></span>';
  const html = escapeHtml(parts[0]) + escapeHtml(parts[1] || '') + gap + escapeHtml(parts.slice(3).join(''));
  return '<div class="vocab-word cloze-sentence' + vocabSizeClass(item.en) + '" dir="ltr" lang="en">' + html + '</div>';
}

/**
 * Render a vocab question's prompt into `el`.
 * `revealed`: the question was answered — show hidden English (listen, cloze).
 */
function renderVocabPrompt(el, q, revealed) {
  let html = '<div class="vocab-label">' + escapeHtml(q.text) + '</div>';
  const item = q.word;
  switch (q.kind) {
    case 'listen':
      html += '<div class="listen-wrap"><button type="button" class="listen-btn" title="השמעה">🔊</button></div>';
      if (revealed) html += vocabWordHtml(item.en, 'en', false);
      break;
    case 'cloze':
      html += clozeSentenceHtml(item, revealed);
      html += '<div class="vocab-sub" dir="rtl">' + escapeHtml(item.he) + '</div>';
      if (revealed) html += '<div class="listen-wrap"><button type="button" class="speak-btn" title="השמעה">🔊</button></div>';
      break;
    case 'en-he':
      html += vocabWordHtml(item.en, 'en', true);
      break;
    default: // he-en, write, order, speak: Hebrew prompt
      html += vocabWordHtml(item.he, 'he', false);
      if (q.kind === 'write') html += '<div class="vocab-hint" dir="ltr">' + vocabHintHtml(item.en) + '</div>';
  }
  el.innerHTML = html;
  el.querySelectorAll('.listen-btn, .speak-btn').forEach(b =>
    b.addEventListener('click', (e) => { e.stopPropagation(); playEnglish(item.en); }));
}

