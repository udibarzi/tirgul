/**
 * @param {HTMLElement} box - container to render into
 * @param {Object} q - order question
 * @param {Object|undefined} answered - saved answer {correct, selected}
 * @param {Function} onDone - (isCorrect, builtSentence) when all tiles are placed
 */
function renderOrderQuestion(box, q, answered, onDone) {
  if (answered) {
    box.innerHTML = '<div class="order-answer done ' + (answered.correct ? 'ok' : 'bad') + '" dir="ltr" lang="en">' +
      escapeHtml(answered.selected) + '</div>';
    return;
  }
  const placed = [];                       // indexes into q.tiles
  box.innerHTML =
    '<div class="order-answer" dir="ltr" lang="en"></div>' +
    '<div class="order-pool" dir="ltr" lang="en"></div>' +
    '<div class="order-actions"><button type="button" class="nav-btn order-undo">↩ מחיקה</button></div>';
  const answerEl = box.querySelector('.order-answer');
  const poolEl = box.querySelector('.order-pool');

  const draw = () => {
    answerEl.innerHTML = placed.length
      ? placed.map((ti, pi) => '<button type="button" class="tile placed" data-pi="' + pi + '">' + escapeHtml(q.tiles[ti]) + '</button>').join('') +
        (q.end ? '<span class="order-end">' + escapeHtml(q.end) + '</span>' : '')
      : '<span class="order-placeholder">לחצו על המילים לפי הסדר</span>';
    poolEl.innerHTML = q.tiles.map((t, ti) =>
      '<button type="button" class="tile' + (placed.includes(ti) ? ' used' : '') + '" data-ti="' + ti + '"' +
      (placed.includes(ti) ? ' disabled' : '') + '>' + escapeHtml(t) + '</button>').join('');
    answerEl.querySelectorAll('.tile').forEach(b => b.onclick = () => { placed.splice(+b.dataset.pi, 1); draw(); });
    poolEl.querySelectorAll('.tile:not(.used)').forEach(b => b.onclick = () => {
      placed.push(+b.dataset.ti);
      if (placed.length === q.tiles.length) {
        const built = placed.map(i => q.tiles[i]).join(' ') + q.end;
        onDone(vocabNormalize(built) === vocabNormalize(q.word.en), built);
      } else {
        draw();
      }
    });
  };
  box.querySelector('.order-undo').onclick = () => { placed.pop(); draw(); };
  draw();
}

